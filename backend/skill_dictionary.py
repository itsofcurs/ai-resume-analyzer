def categorize_skill(skill: str) -> str:
    """Return the category of a given skill."""
    skill_lower = skill.lower()
    category_map = {
        "Programming Languages": PROGRAMMING_LANGUAGES,
        "Web Technologies": WEB_TECHNOLOGIES,
        "Databases": DATABASES,
        "Cloud & DevOps": CLOUD_DEVOPS,
        "Data Science & ML": DATA_SCIENCE_ML,
        "Mobile Development": MOBILE_DEVELOPMENT,
        "Testing & QA": TESTING,
        "Security": SECURITY,
        "Soft Skills": SOFT_SKILLS,
        "Tools & Platforms": TOOLS_PLATFORMS,
        "Other Technical": OTHER_TECHNICAL,
    }
    for category, skills_list in category_map.items():
        if skill_lower in [s.lower() for s in skills_list]:
            return category
    return "Other"
